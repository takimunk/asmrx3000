#[derive(Clone, Copy, Debug, PartialEq, Serialize, Deserialize)]
#[serde(deny_unknown_fields, default)]
pub struct PlasmaConfig {
    /// Plasmaspheric hiss level (0..2).
    pub hiss: f32,
    /// Hiss centre frequency, Hz (100..2000).
    pub hiss_hz: f32,
    /// Whistlers per minute (0..120).
    pub whistlers_per_min: f32,
    /// Highest frequency a whistler starts from, Hz (800..8000).
    pub whistler_hz: f32,
    /// Dispersion D, s^½ (10..120): larger = slower fall (longer field lines).
    pub dispersion: f32,
    /// Chorus level (0..2).
    pub chorus: f32,
    /// Lower edge of the chorus band, Hz (200..4000).
    pub chorus_hz: f32,
    /// Narrowband tones level (0..2).
    pub tones: f32,
    /// Tone frequency, Hz (300..6000).
    pub tone_hz: f32,
    /// Linear output gain (0..8).
    pub gain: f32,
}

impl Default for PlasmaConfig {
    fn default() -> Self {
        Self {
            hiss: 1.0,
            hiss_hz: 560.0,
            whistlers_per_min: 0.0,
            whistler_hz: 3000.0,
            dispersion: 40.0,
            chorus: 0.0,
            chorus_hz: 750.0,
            tones: 0.0,
            tone_hz: 2200.0,
            gain: 1.0,
        }
    }
}

impl PlasmaConfig {
    pub fn validate(&self) -> Result<(), String> {
        check("hiss", self.hiss, 0.0, 2.0)?;
        check("hiss_hz", self.hiss_hz, 100.0, 2000.0)?;
        check("whistlers_per_min", self.whistlers_per_min, 0.0, 120.0)?;
        check("whistler_hz", self.whistler_hz, 800.0, 8000.0)?;
        check("dispersion", self.dispersion, 10.0, 120.0)?;
        check("chorus", self.chorus, 0.0, 2.0)?;
        check("chorus_hz", self.chorus_hz, 200.0, 4000.0)?;
        check("tones", self.tones, 0.0, 2.0)?;
        check("tone_hz", self.tone_hz, 300.0, 6000.0)?;
        check("gain", self.gain, 0.0, 8.0)
    }
}

/// One gliding tone: a whistler (falling, Eckersley), a chorus chirp (rising) or a tone drop.
#[derive(Clone, Copy, Default)]
struct Glide {
    on: bool,
    /// Seconds since the start, and total length.
    t: f32,
    len: f32,
    phase: f32,
    amp: f32,
    kind: GlideKind,
    /// Whistler: dispersion and time offset (f = (d / (t + t0))²). Chirp: start Hz and Hz/s.
    a: f32,
    b: f32,
    /// Lowest frequency the glide is allowed to reach (whistler end).
    floor: f32,
}

#[derive(Clone, Copy, Default, PartialEq)]
enum GlideKind {
    #[default]
    Whistler,
    Chirp,
}

impl Glide {
    #[inline]
    fn freq(&self) -> f32 {
        match self.kind {
            GlideKind::Whistler => {
                let x = self.a / (self.t + self.b);
                (x * x).max(self.floor)
            }
            GlideKind::Chirp => self.a + self.b * self.t,
        }
    }

    #[inline]
    fn env(&self) -> f32 {
        let u = (self.t / self.len).clamp(0.0, 1.0);
        match self.kind {
            // Quick rise, most of the energy in the slower low part (recordings: about a
            // third of a whistler's energy is at 0.5–1 kHz), then it sinks into the noise.
            GlideKind::Whistler => (u / 0.08).min(1.0) * (1.0 - u).powf(0.7),
            GlideKind::Chirp => (core::f32::consts::PI * u).sin().powi(2),
        }
    }
}

const GLIDES: usize = 24;

pub struct Plasma {
    sample_rate: f32,
    rng: Rng,
    cfg: PlasmaConfig,
    hiss: [NoiseBand; 2],
    hiss_ou: Ou,
    hiss_level: Smooth,
    /// Steep roll-off above the hiss band (recordings: ~1% of the energy above 1 kHz).
    hiss_lp: [f32; 3],
    glides: [Glide; GLIDES],
    ev_whistler: Events,
    ev_chorus: Events,
    /// Chorus burst activity (log-amplitude OU) and the clustering excitation.
    chorus_ou: Ou,
    chorus_excite: f32,
    /// Pending echo: seconds to go, dispersion, start Hz, amplitude.
    echo: Option<(f32, f32, f32, f32)>,
    sferic: f32,
    sferic_lp: f32,
    tone_phase: f32,
    tone_on: bool,
    tone_timer: f32,
    tone_level: Smooth,
    tone_drift: Ou,
    tone_drop: f32,
    out: Ramp,
}

impl Plasma {
    pub fn new(sample_rate: f32, seed: u64, cfg: PlasmaConfig) -> Self {
        let sr = sample_rate;
        let mut rng = Rng::new(seed);
        Self {
            sample_rate,
            hiss: [NoiseBand::new(cfg.hiss_hz * 0.6, 0.6, sr), NoiseBand::new(cfg.hiss_hz * 1.4, 0.7, sr)],
            hiss_ou: Ou::default(),
            hiss_level: Smooth::new(0.0),
            hiss_lp: [0.0; 3],
            glides: [Glide::default(); GLIDES],
            ev_whistler: Events::new(&mut rng),
            ev_chorus: Events::new(&mut rng),
            chorus_ou: Ou::default(),
            chorus_excite: 0.0,
            echo: None,
            sferic: 0.0,
            sferic_lp: 0.0,
            tone_phase: 0.0,
            tone_on: false,
            tone_timer: rng.range(0.5, 2.0),
            tone_level: Smooth::new(0.0),
            tone_drift: Ou::default(),
            tone_drop: 0.0,
            out: Ramp::new(cfg.gain),
            rng,
            cfg,
        }
    }

    pub fn config(&self) -> &PlasmaConfig {
        &self.cfg
    }

    pub fn plasmasphere_hiss() -> PlasmaConfig {
        PlasmaConfig::default()
    }
    pub fn whistlers() -> PlasmaConfig {
        PlasmaConfig { hiss: 0.25, whistlers_per_min: 40.0, ..Default::default() }
    }
    pub fn chorus() -> PlasmaConfig {
        PlasmaConfig { hiss: 0.15, chorus: 1.0, ..Default::default() }
    }
    pub fn interstellar() -> PlasmaConfig {
        PlasmaConfig { hiss: 0.0, tones: 1.0, ..Default::default() }
    }
    /// All of the near-Earth modes at once, as during a quiet magnetic storm.
    pub fn magnetosphere() -> PlasmaConfig {
        PlasmaConfig { hiss: 0.7, whistlers_per_min: 4.0, chorus: 0.35, ..Default::default() }
    }

    pub fn preset(name: &str) -> Option<PlasmaConfig> {
        Some(match name {
            "plasmasphere_hiss" => Self::plasmasphere_hiss(),
            "whistlers" => Self::whistlers(),
            "chorus" => Self::chorus(),
            "interstellar" => Self::interstellar(),
            "magnetosphere" => Self::magnetosphere(),
            _ => return None,
        })
    }

    pub const PRESETS: &'static [&'static str] = &["plasmasphere_hiss", "whistlers", "chorus", "interstellar", "magnetosphere"];

    fn spawn(&mut self, g: Glide) {
        if let Some(slot) = self.glides.iter_mut().find(|s| !s.on) {
            *slot = g;
        }
    }

    fn whistler(&mut self, d: f32, f0: f32, amp: f32) {
        // Starts at f0 (t0 so that (d/t0)² = f0) and fades out near 0.35–0.65 kHz.
        let t0 = d / f0.sqrt();
        let f_end = self.rng.range(350.0, 650.0).min(f0 * 0.6);
        let len = d / f_end.sqrt() - t0;
        self.spawn(Glide { on: true, t: 0.0, len, phase: 0.0, amp, kind: GlideKind::Whistler, a: d, b: t0, floor: f_end * 0.9 });
    }
}

impl Generator for Plasma {
    fn set_model(&mut self, cfg: &super::ModelConfig) {
        if let super::ModelConfig::Plasma(c) = cfg {
            self.cfg = *c;
        }
    }

    fn render(&mut self, out: &mut [f32], c: &Controls) {
        for chunk in out.chunks_mut(BLOCK) {
            self.render_block(chunk, c);
        }
    }
}

impl Plasma {
    fn render_block(&mut self, out: &mut [f32], _c: &Controls) {
        let sr = self.sample_rate;
        let len = out.len();
        let dt = len as f32 / sr;
        let cfg = self.cfg;

        // Hiss: two wide bands around the centre, intensity wandering (σ ≈ 5.5 dB, τ ≈ 1.5 s).
        let wander = self.hiss_ou.step(dt, 1.5, 0.63, &mut self.rng).clamp(-2.0, 1.5).exp();
        let h = self.hiss_level.step(0.05 * cfg.hiss * wander, dt, 0.05);
        let (f1, f2) = (cfg.hiss_hz * 0.6, cfg.hiss_hz * 1.4);
        self.hiss[0].svf.set(f1, 0.6, sr);
        self.hiss[1].svf.set(f2, 0.7, sr);
        self.hiss[0].gain.to(h * band_norm(f1, 0.6, sr), len);
        self.hiss[1].gain.to(0.6 * h * band_norm(f2, 0.7, sr), len);

        // Chorus bursts: activity wanders (σ ≈ 6 dB) and each chirp briefly raises the rate.
        let activity = self.chorus_ou.step(dt, 3.0, 0.7, &mut self.rng).clamp(-2.5, 1.5).exp();
        let chorus_rate = if cfg.chorus > 0.0 { (3.0 * activity + self.chorus_excite) / sr } else { 0.0 };
        self.chorus_excite *= (-dt / 0.4).exp();

        // Narrowband tones: on for 1–6 s, off for 0.5–4 s; slow drift, occasional quick drop.
        if cfg.tones > 0.0 {
            self.tone_timer -= dt;
            if self.tone_timer <= 0.0 {
                self.tone_on = !self.tone_on;
                self.tone_timer = if self.tone_on { self.rng.range(1.0, 6.0) } else { self.rng.range(0.5, 4.0) };
                if self.tone_on {
                    self.tone_drop = 0.0;
                }
            }
            if self.tone_on && self.tone_drop == 0.0 && self.rng.uniform() < 0.15 * dt {
                self.tone_drop = 1e-3;
            }
        }
        let drift = 1.0 + 0.04 * self.tone_drift.step(dt, 6.0, 1.0, &mut self.rng).clamp(-2.5, 2.5);
        let tone_amp = self.tone_level.step(if self.tone_on { 0.12 * cfg.tones } else { 0.0 }, dt, 0.25);

        let mut white = [0.0f32; BLOCK];
        for w in white[..len].iter_mut() {
            *w = self.rng.bipolar();
        }
        let white = &white[..len];
        out.fill(0.0);
        self.hiss[0].render_add(white, out);
        self.hiss[1].render_add(white, out);
        let a = one_pole_coef((1.8 * cfg.hiss_hz).min(0.45 * sr), sr);
        for o in out.iter_mut() {
            self.hiss_lp[0] += (*o - self.hiss_lp[0]) * a;
            self.hiss_lp[1] += (self.hiss_lp[0] - self.hiss_lp[1]) * a;
            self.hiss_lp[2] += (self.hiss_lp[1] - self.hiss_lp[2]) * a;
            *o = self.hiss_lp[2];
        }
        for v in self.hiss_lp.iter_mut() {
            *v = flush(*v);
        }

        let inv = 1.0 / sr;
        let tau = core::f32::consts::TAU;
        let sferic_a = one_pole_coef(250.0, sr);
        for (i, o) in out.iter_mut().enumerate() {
            // Whistlers: a sferic click, the falling tone, maybe an echo 2D later.
            for _ in 0..self.ev_whistler.tick(cfg.whistlers_per_min / 60.0 / sr, &mut self.rng) {
                let d = cfg.dispersion * self.rng.range(0.75, 1.3);
                let f0 = cfg.whistler_hz * self.rng.range(0.5, 1.0);
                let amp = 0.3 * (0.5 * self.rng.gauss()).exp().min(3.0);
                self.whistler(d, f0, amp);
                // A close companion path: the same stroke along a neighbouring duct.
                if self.rng.uniform() < 0.5 {
                    let d2 = d * self.rng.range(1.04, 1.12);
                    self.whistler(d2, f0, amp * 0.5);
                }
                self.sferic += 0.5 * amp / 0.3;
                if self.rng.uniform() < 0.35 && self.echo.is_none() {
                    self.echo = Some((d / f0.sqrt() + self.rng.range(1.0, 2.0), 2.0 * d, f0 * 0.8, amp * 0.35));
                }
            }
            if let Some((ref mut wait, d, f0, amp)) = self.echo {
                *wait -= inv;
                if *wait <= 0.0 {
                    self.echo = None;
                    self.whistler(d, f0, amp);
                }
            }
            for _ in 0..self.ev_chorus.tick(chorus_rate, &mut self.rng) {
                // Measured: ~0.8 → 1.25 kHz, +800…+2000 Hz/s, mostly 0.15–0.45 s.
                let f0 = cfg.chorus_hz * self.rng.range(0.9, 1.25);
                let slope = self.rng.range(700.0, 1700.0) * cfg.chorus_hz / 750.0;
                let len = self.rng.range(0.15, 0.45);
                let amp = 0.15 * cfg.chorus * (0.4 * self.rng.gauss()).exp().min(3.0);
                let phase = self.rng.uniform();
                self.spawn(Glide { on: true, t: 0.0, len, phase, amp, kind: GlideKind::Chirp, a: f0, b: slope, floor: 0.0 });
                self.chorus_excite += 1.5;
            }

            let mut acc = 0.0;
            for g in self.glides.iter_mut() {
                if !g.on {
                    continue;
                }
                let f = g.freq();
                g.phase = (g.phase + f * inv) % 1.0;
                // A little harmonic content: magnetospheric tones are not pure sines on the
                // receiver (and pure sines sound synthetic).
                let s = (tau * g.phase).sin() + 0.18 * (2.0 * tau * g.phase).sin();
                acc += s * g.amp * g.env();
                g.t += inv;
                if g.t >= g.len {
                    g.on = false;
                }
            }

            // Sferic: a dull broadband click, low-passed.
            if self.sferic > 1e-4 {
                let n = white[i] * self.sferic;
                self.sferic_lp += (n - self.sferic_lp) * sferic_a;
                acc += self.sferic_lp * 0.6;
                self.sferic *= 0.995;
            }

            if tone_amp > 1e-5 {
                let mut f = cfg.tone_hz * drift;
                if self.tone_drop > 0.0 {
                    // Quick drop: −4 kHz/s for ~0.15 s, then the tone breaks off.
                    f -= 4000.0 * self.tone_drop;
                    self.tone_drop += inv;
                    if self.tone_drop > 0.15 {
                        self.tone_drop = 0.0;
                        self.tone_on = false;
                        self.tone_timer = self.rng.range(0.5, 2.0);
                    }
                }
                self.tone_phase = (self.tone_phase + f.max(50.0) * inv) % 1.0;
                // Slightly noisy: the tone's own bandwidth.
                acc += ((tau * self.tone_phase).sin() + 0.05 * white[i]) * tone_amp;
            }
            *o += acc;
        }
        self.sferic = flush(self.sferic);
        self.sferic_lp = flush(self.sferic_lp);
        self.out.to(cfg.gain, len);
        for o in out.iter_mut() {
            *o *= self.out.next();
        }
        self.out.finish();
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    fn render(cfg: PlasmaConfig, seconds: f32) -> Vec<f32> {
        let sr = 48000.0;
        let mut p = Plasma::new(sr, 11, cfg);
        let mut out = vec![0.0; (seconds * sr) as usize];
        for chunk in out.chunks_mut(BLOCK) {
            p.render(chunk, &Controls::default());
        }
        out
    }

    /// Zero-crossing rate as a cheap frequency estimate of a tonal signal.
    fn zc_hz(x: &[f32], sr: f32) -> f32 {
        let n = x.windows(2).filter(|w| (w[0] <= 0.0) != (w[1] <= 0.0)).count();
        n as f32 / 2.0 / (x.len() as f32 / sr)
    }

    #[test]
    fn whistler_falls_by_eckersley() {
        let mut p = Plasma::new(48000.0, 3, PlasmaConfig { hiss: 0.0, ..Default::default() });
        p.whistler(40.0, 3000.0, 1.0);
        let g = p.glides[0];
        assert!((g.freq() - 3000.0).abs() < 1.0);
        let mut later = g;
        later.t = 0.2;
        // f(t) = (D / (t + t0))²
        let want = (40.0 / (0.2 + 40.0 / 3000f32.sqrt())).powi(2);
        assert!((later.freq() - want).abs() < 1.0, "{} vs {want}", later.freq());
        assert!(g.len > 0.4 && g.len < 1.2, "length {} s", g.len);
    }

    #[test]
    fn chorus_sits_in_its_band() {
        let x = render(Plasma::chorus(), 6.0);
        let rms = (x.iter().map(|v| v * v).sum::<f32>() / x.len() as f32).sqrt();
        assert!(rms > 1e-3, "chorus is audible: {rms}");
    }

    #[test]
    fn interstellar_tone_near_2_khz() {
        let x = render(Plasma::interstellar(), 8.0);
        // The loudest second should be a tone near tone_hz.
        let sr = 48000.0;
        let best = x
            .chunks(sr as usize)
            .max_by(|a, b| a.iter().map(|v| v * v).sum::<f32>().partial_cmp(&b.iter().map(|v| v * v).sum::<f32>()).unwrap())
            .unwrap();
        let f = zc_hz(best, sr);
        assert!((1700.0..2700.0).contains(&f), "{f} Hz");
    }

    #[test]
    fn hiss_is_low_and_finite() {
        let x = render(Plasma::plasmasphere_hiss(), 4.0);
        assert!(x.iter().all(|v| v.is_finite()));
        assert!(zc_hz(&x, 48000.0) < 1500.0);
    }
}
