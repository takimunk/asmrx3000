//! Space plasma waves made audible: the "sounds of space" that spacecraft record as radio
//! and plasma-wave signals in the audio band (Van Allen Probes EMFISIS, Cassini RPWS,
//! Voyager PWS). Each layer follows the physics of its wave mode; the levels, bands and
//! sweep rates are fitted to NASA recordings (assets/sounds/space, measured with a
//! spectrogram: band shares, centroid, level spread, tonal tracks).
//!
//! * **Hiss** (plasmaspheric hiss): incoherent whistler-mode noise inside the plasmasphere.
//!   Broadband noise, centroid ≈ 470 Hz, nearly all of it below 1 kHz; its intensity
//!   wanders slowly (p10–p90 spread ≈ 14 dB over 1 s frames).
//! * **Whistlers**: a lightning stroke's broadband pulse travels along a field line through
//!   the dispersive magnetospheric plasma. Low frequencies are slower: arrival time
//!   t(f) = D / √f (Eckersley's law, dispersion D in s^½), so a whistler is a falling tone,
//!   f(t) = (D / (t + t₀))². Recordings fall from ~1.4–3 kHz to ~0.75 kHz in ~0.5 s. Each
//!   follows a sferic click; part of the energy bounces back from the conjugate hemisphere
//!   and returns as an echo of twice the dispersion.
//! * **Chorus**: whistler-mode emissions generated by electrons near the equator. Discrete
//!   rising chirps ("dawn chorus"), measured at +800…+2000 Hz/s, 0.2–0.6 s, ~0.8 → 1.25 kHz,
//!   in bursts (level spread ≈ 15 dB).
//! * **Tones** (Voyager's interstellar plasma oscillations, narrowband radio emissions):
//!   steady narrow tones at ~1.8–2.4 kHz that drift slowly, break off, and now and then
//!   drop quickly (−3…−7 kHz/s for ~0.1–0.2 s).

